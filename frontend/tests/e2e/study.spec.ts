import { test, expect } from '@playwright/test';

test('login, independent chat, streaming greeting, blank quiz, refresh and logout', async ({ page, request }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.locator('#landing-register-btn').click();
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel('Username').fill('user');
  await page.getByLabel('Password', { exact: true }).fill('wrong');
  await page.locator('#login-submit').click();
  await expect(page.getByRole('alert')).toContainText('Invalid');
  await page.getByLabel('Password', { exact: true }).fill('user');
  await page.locator('#login-submit').click();
  await expect(page).toHaveURL(/\/app$/);
  await page.locator('#new-chat-btn').click();
  await expect(page.getByLabel('Question')).toBeVisible();
  const chatUrl = page.url();
  await page.getByLabel('Question').fill('Who are you?');
  await page.locator('#chat-send-btn').click();
  await expect(page.locator('.message.assistant')).toContainText('study assistant', { timeout: 30000 });
  await page.screenshot({ path: 'test-results/chat-desktop.png', fullPage: true });
  await page.locator('#tab-quiz').click();
  await expect(page.getByLabel('Quiz', { exact: true })).toBeEmpty();
  await page.reload();
  await expect(page.getByLabel('Quiz', { exact: true })).toBeVisible();
  await page.locator('#new-chat-btn').click();
  await expect(page.locator('.message')).toHaveCount(0);
  await page.goto(chatUrl);
  await expect(page.locator('.message.assistant')).toContainText('study assistant');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Toggle menu' }).click();
  await expect(page.locator('.sidebar')).toBeVisible();
  await page.screenshot({ path: 'test-results/chat-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Logout' }).click();
  await expect(page).toHaveURL(/\/login$/);
  expect(errors).toEqual([]);
  expect((await request.get('/api/v1/no-such-route')).status()).toBe(404);
});
